DROP TABLE EMPLOYEE;

CREATE TABLE EMPLOYEE
(
    EMP_ID NUMBER(5),
    EMP_NAME VARCHAR2(30),
    AGE NUMBER(3),
    BASIC_SAL NUMBER(10,2)
);


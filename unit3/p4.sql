SET SERVEROUTPUT ON;

DECLARE
    V_SALARY EMPLOYEE.BASIC_SAL%TYPE;
BEGIN
    SELECT BASIC_SAL
    INTO V_SALARY
    FROM EMPLOYEE
    WHERE AGE = 50;

    DBMS_OUTPUT.PUT_LINE('Basic Salary: ' || V_SALARY);

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        DBMS_OUTPUT.PUT_LINE('No employee found whose age is 50.');

    WHEN TOO_MANY_ROWS THEN
        DBMS_OUTPUT.PUT_LINE('More than one employee is 50 years old.');
END;
